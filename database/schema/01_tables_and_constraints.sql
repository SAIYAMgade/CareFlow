-- Drop tables if existing (in reverse dependency order)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'AUDIT_LOG', 'STATUS_HISTORY', 'DATA_QUALITY_ISSUES', 'RESULTS',
        'ORDERS', 'OBSERVATIONS', 'ENCOUNTERS', 'APPOINTMENTS', 'PATIENTS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- 1. PATIENTS Table
CREATE TABLE PATIENTS (
    patient_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    mrn                 VARCHAR2(32) NOT NULL,
    first_name          VARCHAR2(100) NOT NULL,
    last_name           VARCHAR2(100) NOT NULL,
    date_of_birth       DATE NOT NULL,
    gender              VARCHAR2(10) DEFAULT 'UNKNOWN' NOT NULL,
    phone               VARCHAR2(30),
    email               VARCHAR2(150),
    address             VARCHAR2(255),
    status              VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_patients_mrn UNIQUE (mrn),
    CONSTRAINT chk_patients_gender CHECK (gender IN ('FEMALE', 'MALE', 'OTHER', 'UNKNOWN')),
    CONSTRAINT chk_patients_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'MERGED'))
);

-- 2. APPOINTMENTS Table
CREATE TABLE APPOINTMENTS (
    appointment_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    patient_id          NUMBER NOT NULL,
    appointment_time    TIMESTAMP WITH TIME ZONE NOT NULL,
    appointment_type    VARCHAR2(50) DEFAULT 'FOLLOW_UP' NOT NULL,
    department          VARCHAR2(80) NOT NULL,
    provider_name       VARCHAR2(120) NOT NULL,
    status              VARCHAR2(30) DEFAULT 'SCHEDULED' NOT NULL,
    check_in_time       TIMESTAMP WITH TIME ZONE,
    cancel_reason       VARCHAR2(255),
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_appts_patient FOREIGN KEY (patient_id) 
        REFERENCES PATIENTS(patient_id),
    CONSTRAINT chk_appts_status CHECK (status IN (
        'SCHEDULED', 'CHECKED_IN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'NO_SHOW'
    ))
);

-- 3. ENCOUNTERS Table
CREATE TABLE ENCOUNTERS (
    encounter_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    patient_id          NUMBER NOT NULL,
    appointment_id      NUMBER,
    encounter_type      VARCHAR2(50) DEFAULT 'OUTPATIENT' NOT NULL,
    department          VARCHAR2(80) NOT NULL,
    provider_name       VARCHAR2(120) NOT NULL,
    status              VARCHAR2(30) DEFAULT 'OPEN' NOT NULL,
    start_time          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    end_time            TIMESTAMP WITH TIME ZONE,
    chief_complaint     VARCHAR2(500),
    clinical_notes      CLOB,
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_enc_patient FOREIGN KEY (patient_id) 
        REFERENCES PATIENTS(patient_id),
    CONSTRAINT fk_enc_appointment FOREIGN KEY (appointment_id) 
        REFERENCES APPOINTMENTS(appointment_id),
    CONSTRAINT chk_enc_status CHECK (status IN (
        'OPEN', 'IN_PROGRESS', 'AWAITING_RESULTS', 'COMPLETED', 'CANCELLED'
    )),
    CONSTRAINT chk_enc_time_order CHECK (end_time IS NULL OR end_time >= start_time)
);

-- 4. OBSERVATIONS Table
CREATE TABLE OBSERVATIONS (
    observation_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    encounter_id        NUMBER NOT NULL,
    patient_id          NUMBER NOT NULL,
    observation_type    VARCHAR2(50) NOT NULL,
    observation_code    VARCHAR2(30) NOT NULL,
    value_numeric       NUMBER(10, 2),
    value_text          VARCHAR2(255),
    unit                VARCHAR2(30),
    observation_time    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    status              VARCHAR2(20) DEFAULT 'FINAL' NOT NULL,
    source              VARCHAR2(50) DEFAULT 'CLINICAL_TRIAGE' NOT NULL,
    CONSTRAINT fk_obs_encounter FOREIGN KEY (encounter_id) 
        REFERENCES ENCOUNTERS(encounter_id),
    CONSTRAINT fk_obs_patient FOREIGN KEY (patient_id) 
        REFERENCES PATIENTS(patient_id),
    CONSTRAINT chk_obs_status CHECK (status IN ('PRELIMINARY', 'FINAL', 'AMENDED', 'CANCELLED'))
);

-- 5. ORDERS Table
CREATE TABLE ORDERS (
    order_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    encounter_id        NUMBER NOT NULL,
    patient_id          NUMBER NOT NULL,
    order_type          VARCHAR2(50) DEFAULT 'LABORATORY' NOT NULL,
    order_code          VARCHAR2(50) NOT NULL,
    order_name          VARCHAR2(150) NOT NULL,
    order_status        VARCHAR2(30) DEFAULT 'ORDERED' NOT NULL,
    priority            VARCHAR2(20) DEFAULT 'ROUTINE' NOT NULL,
    ordered_by          VARCHAR2(120) NOT NULL,
    ordered_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_ord_encounter FOREIGN KEY (encounter_id) 
        REFERENCES ENCOUNTERS(encounter_id),
    CONSTRAINT fk_ord_patient FOREIGN KEY (patient_id) 
        REFERENCES PATIENTS(patient_id),
    CONSTRAINT chk_ord_status CHECK (order_status IN ('ORDERED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_ord_priority CHECK (priority IN ('STAT', 'URGENT', 'ROUTINE')),
    CONSTRAINT chk_ord_completion_time CHECK (completed_at IS NULL OR completed_at >= ordered_at)
);

-- 6. RESULTS Table
CREATE TABLE RESULTS (
    result_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    order_id            NUMBER NOT NULL,
    result_value        VARCHAR2(100) NOT NULL,
    reference_range     VARCHAR2(100),
    unit                VARCHAR2(30),
    abnormal_flag       VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    result_status       VARCHAR2(30) DEFAULT 'PENDING_REVIEW' NOT NULL,
    reviewed_by         VARCHAR2(120),
    reviewed_at         TIMESTAMP WITH TIME ZONE,
    result_time         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_res_order UNIQUE (order_id),
    CONSTRAINT fk_res_order FOREIGN KEY (order_id) 
        REFERENCES ORDERS(order_id),
    CONSTRAINT chk_res_flag CHECK (abnormal_flag IN ('NORMAL', 'HIGH', 'LOW', 'CRITICAL')),
    CONSTRAINT chk_res_status CHECK (result_status IN ('PENDING_REVIEW', 'REVIEWED', 'AMENDED'))
);

-- 7. DATA_QUALITY_ISSUES Table
CREATE TABLE DATA_QUALITY_ISSUES (
    issue_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    rule_code           VARCHAR2(50) NOT NULL,
    severity            VARCHAR2(20) NOT NULL,
    affected_entity     VARCHAR2(50) NOT NULL,
    entity_id           NUMBER NOT NULL,
    detection_time      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    description         VARCHAR2(500) NOT NULL,
    investigation_steps VARCHAR2(1000) NOT NULL,
    resolution_status   VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    resolved_by         VARCHAR2(120),
    resolved_at         TIMESTAMP WITH TIME ZONE,
    remediation_notes   VARCHAR2(1000),
    CONSTRAINT chk_dq_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_dq_res_status CHECK (resolution_status IN ('OPEN', 'INVESTIGATING', 'RESOLVED', 'FALSE_POSITIVE'))
);

-- 8. AUDIT_LOG Table
CREATE TABLE AUDIT_LOG (
    audit_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    entity_type         VARCHAR2(50) NOT NULL,
    entity_id           NUMBER NOT NULL,
    action              VARCHAR2(50) NOT NULL,
    actor               VARCHAR2(120) NOT NULL,
    previous_state      CLOB,
    new_state           CLOB,
    correlation_id      VARCHAR2(64),
    reason              VARCHAR2(255),
    changed_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- 9. STATUS_HISTORY Table
CREATE TABLE STATUS_HISTORY (
    history_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    entity_type         VARCHAR2(50) NOT NULL,
    entity_id           NUMBER NOT NULL,
    from_status         VARCHAR2(30),
    to_status           VARCHAR2(30) NOT NULL,
    actor               VARCHAR2(120) NOT NULL,
    reason              VARCHAR2(255),
    changed_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
